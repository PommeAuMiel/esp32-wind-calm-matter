"""Exercise the installed HWCDC TX code with a bounded host/RTOS model.

The real write, availableForWrite, timeout setter and disconnected FIFO policy
are compiled, along with the Serial configuration extracted from setup(). The
model simulates USB backpressure, not a UART transport or the USB peripheral.
No fan/controller command can be generated by this fixture.
"""
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
CDC_SOURCE = ROOT / ".local/dedicated/arduino/cores/esp32/HWCDC.cpp"
APP_SOURCE = ROOT / "firmware/WindCalmController/Application.cpp"


def extract_function(source, signature):
    match = re.search(signature + r"\s*\{", source)
    if match is None:
        raise AssertionError("Required installed HWCDC function is missing")
    # Braces in comments and literals must not truncate the real function.
    tokens = re.finditer(
        r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|'
        r"'(?:\\.|[^'\\])*'|[{}]", source[match.end():])
    depth = 1
    for token in tokens:
        if token.group() == "{":
            depth += 1
        elif token.group() == "}":
            depth -= 1
        if not depth:
            return source[match.start():match.end() + token.end()]
    raise AssertionError("Required installed HWCDC function is incomplete")


def extract_usb_setup(source):
    setup = extract_function(source, r"void\s+begin\s*\(\s*const Config &config\s*\)")
    calls = []
    for name in ("begin", "setTxTimeoutMs"):
        match = re.search(r"\bSerial\." + name + r"\s*\([^;]*\)\s*;", setup)
        if match is None:
            raise AssertionError("Application USB setup is incomplete")
        calls.append(match.group())
    return "static void configure_from_application() {\n" + "\n".join(calls) + "\n}\n"


STUBS = r"""
#include <algorithm>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <stdexcept>
#include <string>
#include <vector>

using BaseType_t = int;
using UBaseType_t = uint32_t;
using TickType_t = uint32_t;
constexpr BaseType_t pdPASS = 1;
constexpr BaseType_t pdTRUE = 1;
constexpr uint32_t portTICK_PERIOD_MS = 1;
static int ring_device, lock_device;
static void *tx_ring_buf = &ring_device;
static void *tx_lock = &lock_device;
static bool connected = true;
static bool plugged = true;
static bool mutex_available = true;
static size_t capacity = 64;
static std::vector<uint8_t> usb_queue;
static std::vector<uint8_t> removed_bytes;
static std::vector<uint32_t> requested_waits;
static uint64_t elapsed_ms = 0;
static unsigned send_attempts = 0, kicks = 0, fifo_flushes = 0;

static void require(bool condition, const char *reason) {
    if (!condition) throw std::runtime_error(reason);
}
static void record_wait(uint32_t ticks, bool timed_out) {
    requested_waits.push_back(ticks);
    if (timed_out) elapsed_ms += uint64_t(ticks) * portTICK_PERIOD_MS;
}
BaseType_t xSemaphoreTake(void *semaphore, uint32_t ticks) {
    require(semaphore == &lock_device, "Wrong USB semaphore");
    record_wait(ticks, !mutex_available);
    return mutex_available ? pdPASS : 0;
}
void xSemaphoreGive(void *semaphore) {
    require(semaphore == &lock_device, "Wrong USB semaphore release");
}
size_t xRingbufferGetMaxItemSize(void *ring) {
    require(ring == &ring_device, "Wrong USB ring buffer");
    return capacity;
}
size_t xRingbufferGetCurFreeSize(void *ring) {
    require(ring == &ring_device, "Wrong USB ring buffer");
    require(usb_queue.size() <= capacity, "USB ring overflow");
    return capacity - usb_queue.size();
}
BaseType_t xRingbufferSend(void *ring, void *data, size_t size, uint32_t ticks) {
    require(ring == &ring_device, "Wrong USB ring buffer");
    require(data != nullptr && size > 0, "Invalid USB enqueue");
    ++send_attempts;
    const bool fits = size <= capacity - usb_queue.size();
    record_wait(ticks, !fits);
    if (!fits) return 0;
    const auto *bytes = static_cast<const uint8_t *>(data);
    usb_queue.insert(usb_queue.end(), bytes, bytes + size);
    return pdTRUE;
}
void vRingbufferGetInfo(void *ring, UBaseType_t *, UBaseType_t *, UBaseType_t *,
                       UBaseType_t *, UBaseType_t *waiting) {
    require(ring == &ring_device, "Wrong USB ring buffer");
    *waiting = UBaseType_t(usb_queue.size());
}
void *xRingbufferReceiveUpTo(void *ring, size_t *size, uint32_t ticks, size_t limit) {
    require(ring == &ring_device, "Wrong USB ring buffer");
    record_wait(ticks, false);
    *size = std::min(limit, usb_queue.size());
    removed_bytes.assign(usb_queue.begin(), usb_queue.begin() + *size);
    usb_queue.erase(usb_queue.begin(), usb_queue.begin() + *size);
    return removed_bytes.empty() ? nullptr : removed_bytes.data();
}
void vRingbufferReturnItem(void *ring, void *item) {
    require(ring == &ring_device && item == removed_bytes.data(), "Wrong USB returned item");
}
void hw_cdc_clear_tx_stash() {}
void hw_cdc_enable_tx_intr() { ++kicks; }
void usb_serial_jtag_ll_txfifo_flush() { ++fifo_flushes; }

class HWCDC {
 public:
    void begin(unsigned long baud) { require(baud == 115200, "Unexpected application USB baud"); }
    void setTxTimeoutMs(uint32_t timeout);
    int availableForWrite();
    size_t write(const uint8_t *buffer, size_t size);
    static bool isCDC_Connected() { return connected; }
    static bool isPlugged() { return plugged; }
};
static HWCDC Serial;
"""


SCENARIOS = r"""
static void reset_model(size_t ring_capacity, bool full) {
    capacity = ring_capacity;
    usb_queue.clear();
    if (full) usb_queue.assign(capacity, 0xA5);
    removed_bytes.clear(); requested_waits.clear();
    elapsed_ms = 0; send_attempts = kicks = fifo_flushes = 0;
    connected = plugged = mutex_available = true;
}
static void expect_no_waits() {
    require(elapsed_ms == 0, "USB TX delayed the control task");
    for (const auto ticks : requested_waits)
        require(ticks == 0, "Application configured a blocking USB wait");
}
int main(int argc, char **argv) {
    require(argc == 2, "A scenario is required");
    const std::string scenario = argv[1];
    const uint8_t line[] = {'S', 'T', 'A', 'T', 'U', 'S', '\n'};
    if (scenario == "four_lines") {
        // The source's default timeout runs first, with a host that is still
        // considered connected but never consumes its already-full USB ring.
        reset_model(64, true);
        const auto original_queue = usb_queue;
        for (unsigned line_number = 0; line_number < 4; ++line_number)
            require(Serial.write(line, sizeof(line)) == 0, "Backpressure must return short writes");
        require(elapsed_ms == 8000 && send_attempts == 80, "Original four-line stall was not reproduced");
        require(usb_queue == original_queue, "Blocked writes changed already-queued bytes");
        require(connected && fifo_flushes == 0, "Host backpressure was treated as a disconnect");
        std::printf("HWCDC default: four blocked lines = %llu ms, %u attempts\n",
                    static_cast<unsigned long long>(elapsed_ms), send_attempts);
        configure_from_application();
        reset_model(64, true);
        for (unsigned line_number = 0; line_number < 4; ++line_number)
            require(Serial.write(line, sizeof(line)) == 0, "Backpressure must return short writes");
        expect_no_waits();
        require(send_attempts == 80 && usb_queue == original_queue, "Retry cap or queue changed");
        std::printf("HWCDC application: four blocked lines = %llu ms, %u attempts\n",
                    static_cast<unsigned long long>(elapsed_ms), send_attempts);
    } else if (scenario == "mutex_busy") {
        configure_from_application(); reset_model(64, false);
        mutex_available = false;
        require(Serial.write(line, sizeof(line)) == 0, "A busy mutex must return immediately");
        require(Serial.availableForWrite() == 0, "A busy mutex reported TX capacity");
        expect_no_waits();
        require(send_attempts == 0 && usb_queue.empty(), "Busy mutex allowed USB enqueue");
    } else if (scenario == "capacity") {
        configure_from_application(); reset_model(64, false);
        require(Serial.availableForWrite() == 64, "Empty USB TX capacity is incorrect");
        require(Serial.write(line, sizeof(line)) == sizeof(line), "Available USB space lost a line");
        require(Serial.availableForWrite() == int(64 - sizeof(line)), "USB TX capacity did not decrease");
        require(usb_queue == std::vector<uint8_t>(line, line + sizeof(line)), "USB bytes were changed");
        require(send_attempts == 1, "A successful line was retried");
        expect_no_waits();
    } else if (scenario == "partial_prefix") {
        configure_from_application(); reset_model(64, false);
        std::vector<uint8_t> bytes(100);
        for (size_t index = 0; index < bytes.size(); ++index) bytes[index] = uint8_t(index);
        require(Serial.write(bytes.data(), bytes.size()) == 64, "Partial USB write length is incorrect");
        require(usb_queue == std::vector<uint8_t>(bytes.begin(), bytes.begin() + 64), "Queued prefix was dropped or changed");
        require(send_attempts == 21, "Partial write exceeded its 20 consecutive failure cap");
        require(connected && fifo_flushes == 0, "Partial host backpressure flushed the queue");
        expect_no_waits();
    } else if (scenario == "disconnected_fifo") {
        configure_from_application(); reset_model(16, true);
        for (size_t index = 0; index < usb_queue.size(); ++index) usb_queue[index] = uint8_t(index);
        connected = plugged = false;
        const uint8_t newest[] = {40, 41, 42, 43};
        require(Serial.write(newest, sizeof(newest)) == sizeof(newest), "Disconnected FIFO write was rejected");
        std::vector<uint8_t> expected;
        for (uint8_t byte = 4; byte < 16; ++byte) expected.push_back(byte);
        expected.insert(expected.end(), newest, newest + sizeof(newest));
        require(usb_queue == expected, "Disconnected FIFO did not replace the oldest bytes");
        require(send_attempts == 1 && fifo_flushes == 1 && kicks == 1, "Disconnected FIFO made unexpected retries");
        expect_no_waits();
    } else if (scenario == "invalid_writes") {
        configure_from_application(); reset_model(64, false);
        require(Serial.write(nullptr, sizeof(line)) == 0, "Null USB data was accepted");
        require(Serial.write(line, 0) == 0, "Empty USB data was accepted");
        require(requested_waits.empty() && send_attempts == 0 && usb_queue.empty(), "Invalid USB write changed state");
    } else {
        throw std::runtime_error("Unknown scenario");
    }
    std::printf("HWCDC backpressure: %s passed\n", argv[1]);
}
"""


class UsbBackpressureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not CDC_SOURCE.is_file():
            raise unittest.SkipTest("The private Arduino SDK is not installed")
        compiler = shutil.which("clang++") or shutil.which("g++")
        if not compiler:
            raise unittest.SkipTest("A host C++ compiler is not installed")
        installed = CDC_SOURCE.read_text()
        timeout = re.search(r"static\s+uint32_t\s+tx_timeout_ms\s*=\s*[^;]+;", installed)
        if timeout is None:
            raise AssertionError("The installed HWCDC default timeout is missing")
        signatures = (
            r"static\s+void\s+flushTXBuffer\s*\([^)]*\)",
            r"void\s+HWCDC::setTxTimeoutMs\s*\([^)]*\)",
            r"int\s+HWCDC::availableForWrite\s*\(\s*void\s*\)",
            r"size_t\s+HWCDC::write\s*\(\s*const\s+uint8_t\s*\*\s*buffer\s*,\s*size_t\s+size\s*\)",
        )
        actual = timeout.group() + "\n" + "\n".join(
            extract_function(installed, signature) for signature in signatures)
        directory = tempfile.TemporaryDirectory()
        cls.addClassCleanup(directory.cleanup)
        source = Path(directory.name) / "usb_backpressure_test.cpp"
        source.write_text(STUBS + actual + extract_usb_setup(APP_SOURCE.read_text()) + SCENARIOS)
        cls.binary = str(Path(directory.name) / "usb_backpressure_test")
        subprocess.run([compiler, "-std=c++17", "-Wall", "-Wextra", "-Werror",
                        "-fsanitize=address,undefined", "-g", str(source),
                        "-o", cls.binary], check=True)

    def run_scenario(self, scenario):
        # A fresh process preserves the SDK initializer for the before/after case.
        result = subprocess.run([self.binary, scenario], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        print(result.stdout, end="")

    def test_four_status_lines_stop_causing_eight_second_stall(self):
        self.run_scenario("four_lines")

    def test_busy_mutex_never_waits_or_enqueues(self):
        self.run_scenario("mutex_busy")

    def test_available_capacity_and_successful_line(self):
        self.run_scenario("capacity")

    def test_partial_write_preserves_already_queued_prefix(self):
        self.run_scenario("partial_prefix")

    def test_disconnected_fifo_remains_bounded(self):
        self.run_scenario("disconnected_fifo")

    def test_empty_or_null_writes_leave_usb_queue_untouched(self):
        self.run_scenario("invalid_writes")


if __name__ == "__main__":
    unittest.main()
